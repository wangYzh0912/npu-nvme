#!/usr/bin/env python3
"""Render the requested training/inference AIC/AIV activity comparison."""
from __future__ import annotations
import argparse, csv, json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

def load_bins(path):
    rows=list(csv.DictReader(open(path)))
    x=np.array([float(r['start_ns'])/1e6 for r in rows])
    e=np.r_[x,float(rows[-1]['end_ns'])/1e6]
    return e, np.array([100*(float(r['aic_only'])+float(r['both'])) for r in rows]), np.array([100*(float(r['aiv_only'])+float(r['both'])) for r in rows]), np.array([100*float(r['unknown']) for r in rows])

def stage_spans(summary):
    d=json.load(open(summary)); colours={'forward':'#2878b5','backward':'#cb5555','recompute':'#ad6aaf','optimizer':'#5c9e53','communication':'#8e8169','input':'#6ca7ad','unclassified':'#bcbcbc'}
    spans=[]
    # stage_union_ns is a duration union only; for a compact comparison, use
    # the labeled task tracks generated by the analysis as the stage legend.
    return colours, list(d.get('stage_union_ns',{}))

def main():
    p=argparse.ArgumentParser();p.add_argument('--train-bins',type=Path,required=True);p.add_argument('--train-summary',type=Path,required=True);p.add_argument('--infer-bins',type=Path,required=True);p.add_argument('--infer-summary',type=Path,required=True);p.add_argument('--infer-stages',type=Path);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    te,ta,tv,tu=load_bins(a.train_bins); ie,ia,iv,iu=load_bins(a.infer_bins)
    fig,axs=plt.subplots(2,1,figsize=(15,8),sharey=True,gridspec_kw={'hspace':.24})
    for ax,e,aic,aiv,unknown,title,summary in ((axs[0],te,ta,tv,tu,'Training: Qwen3-8B MindSpore, TP4, seq128, pilot rank0',a.train_summary),(axs[1],ie,ia,iv,iu,'Inference: Qwen3-8B vLLM-Ascend, TP4, pilot device',a.infer_summary)):
        x=e[:-1]; ax.stairs(aic,e,label='AIC task activity',color='#275dad',linewidth=1.1);ax.stairs(aiv,e,label='AIV task activity',color='#da780f',linewidth=1.1)
        ax.fill_between(x,0,100*unknown,step='post',color='#7e43ad',alpha=.14,label='mixed task envelope (unknown)' if title.startswith('Training') else None)
        ax.set_ylim(0,105);ax.grid(alpha=.2);ax.set_ylabel('Active task time per 1 ms (%)');ax.set_title(title,loc='left',fontsize=12,weight='bold');ax.legend(loc='upper right',ncol=3,fontsize=9)
        if title.startswith('Training'):
            ax.text(.01,.02,'Stage labels are shown in the companion detailed timeline.',transform=ax.transAxes,fontsize=8,color='#475569')
    if a.infer_stages:
        d=json.load(open(a.infer_summary)); origin=float(d['time_origin_us']); stages=json.load(open(a.infer_stages))
        spans=[]
        for s in stages:
            lo=(s['begin_ns']/1000-origin)/1000;hi=(s['end_ns']/1000-origin)/1000
            if hi>0 and lo<(ie[-1]):spans.append((s,lo,hi))
        if spans:
            left=max(0,min(x[1] for x in spans)-200);right=min(ie[-1],max(x[2] for x in spans)+200)
            axs[1].set_xlim(left,right)
            for i,(s,lo,hi) in enumerate(spans):
                axs[1].axvspan(lo,hi,color=('#dbeafe' if i==0 else '#ffedd5'),alpha=.42,zorder=0)
                axs[1].text((lo+hi)/2,102,f"{s['stage']} (batch {s['batch']})",ha='center',va='bottom',fontsize=8,color='#334155')
    axs[1].set_xlabel('Time from trace window start (ms)')
    fig.suptitle('AIC/AIV activity comparison — device-task envelopes',fontsize=15,weight='bold')
    fig.text(.01,.01,'Task activity is an execution-envelope measure, not core occupancy. Purple regions are mixed-engine intervals (unknown engine split). Inference request spans are host wall-clock intervals aligned to device timestamps.',fontsize=9)
    fig.tight_layout(rect=(0,.04,1,.95));a.output.parent.mkdir(parents=True,exist_ok=True)
    for ext in ('png','svg','pdf'):fig.savefig(a.output.with_suffix('.'+ext),dpi=180)

if __name__=='__main__':main()
